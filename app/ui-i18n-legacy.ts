// Translate an English UI string for the active locale. Korean is passed in from
// the call site; any locale/string without an entry falls back to English.
export function tr(locale: Locale, en: string, ko?: string): string {
  if (locale === "ko") return ko ?? en;
  if (locale === "en") return en;
  return targetedDict[en]?.[locale]
    ?? dict[en]?.[locale]
    ?? multi[en]?.[locale]
    ?? multi2[en]?.[locale]
    ?? appDict[en]?.[locale]
    ?? curriculumDict[en]?.[locale]
    ?? setupDict[en]?.[locale]
    ?? fillDict[en]?.[locale]
    ?? restDict[en]?.[locale]
    ?? (locale === "ja" ? jaDict[en] : undefined)
    ?? en;
}
