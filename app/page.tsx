/* One master volume for every generated sound. The header exposes it as a
   three-step control, so all three synths have to read the same value. */
let uiSoundVolume = 1;
export function setUiSoundVolume(v: number) { uiSoundVolume = Math.max(0, Math.min(1, v)); }

function playTypewriterReturnSound() {
  if (typeof document !== "undefined" && document.visibilityState === "hidden") return;
  const AudioContextConstructor = window.AudioContext
    ?? (window as typeof window & { webkitAudioContext?: typeof AudioContext }).webkitAudioContext;
  if (!AudioContextConstructor) return;

  const context = new AudioContextConstructor();
  if (context.state === "suspended") void context.resume();
  const now = context.currentTime + 0.01;

  // A gentle master bus keeps the layered sound cohesive and avoids clipping.
  const master = context.createGain();
  master.gain.value = 0.9 * uiSoundVolume;
  const warmth = context.createBiquadFilter();
  warmth.type = "lowpass";
  warmth.frequency.value = 8200;
  master.connect(warmth).connect(context.destination);

  const makeNoise = (seconds: number) => {
    const buffer = context.createBuffer(1, Math.max(1, Math.floor(context.sampleRate * seconds)), context.sampleRate);
    const data = buffer.getChannelData(0);
    for (let index = 0; index < data.length; index += 1) {
      data[index] = (Math.random() * 2 - 1) * (1 - index / data.length);
    }
    return buffer;
  };

  // Phase 1 — the ratcheting carriage drag: a run of short filtered-noise ticks
  // that accelerate slightly, like the platen spinning back.
  const ticks = 17;
  let dragEnd = now;
  for (let index = 0; index < ticks; index += 1) {
    const start = now + index * 0.023 * (1 - index * 0.018);
    dragEnd = start;
    const length = 0.014;
    const source = context.createBufferSource();
    source.buffer = makeNoise(length);
    const filter = context.createBiquadFilter();
    filter.type = "bandpass";
    filter.frequency.value = 880 + index * 42;
    filter.Q.value = 3.2;
    const gain = context.createGain();
    const amplitude = 0.06 * (1 - (index / ticks) * 0.55);
    gain.gain.setValueAtTime(amplitude, start);
    gain.gain.exponentialRampToValueAtTime(0.0004, start + length);
    source.connect(filter).connect(gain).connect(master);
    source.start(start);
    source.stop(start + length + 0.004);
  }
  dragEnd += 0.03;

  // Phase 2 — a low mechanical thunk as the carriage seats at the margin.
  const thunk = context.createOscillator();
  const thunkGain = context.createGain();
  thunk.type = "sine";
  thunk.frequency.setValueAtTime(150, dragEnd);
  thunk.frequency.exponentialRampToValueAtTime(68, dragEnd + 0.12);
  thunkGain.gain.setValueAtTime(0.0001, dragEnd);
  thunkGain.gain.exponentialRampToValueAtTime(0.12, dragEnd + 0.006);
  thunkGain.gain.exponentialRampToValueAtTime(0.0006, dragEnd + 0.14);
  thunk.connect(thunkGain).connect(master);
  thunk.start(dragEnd);
  thunk.stop(dragEnd + 0.16);

  // Phase 3 — the bell "ding": inharmonic partials (a real bell is not a pure
  // tone) plus a bright metallic strike transient, with a long ringing decay.
  const bellStart = dragEnd + 0.012;
  const base = 1046.5; // ~C6
  const partials = [
    { ratio: 1, gain: 0.22, decay: 0.95 },
    { ratio: 2.41, gain: 0.10, decay: 0.72 },
    { ratio: 3.86, gain: 0.06, decay: 0.52 },
    { ratio: 5.18, gain: 0.035, decay: 0.4 },
  ];
  for (const partial of partials) {
    const bell = context.createOscillator();
    const bellGain = context.createGain();
    bell.type = "sine";
    bell.frequency.value = base * partial.ratio;
    bellGain.gain.setValueAtTime(0.0001, bellStart);
    bellGain.gain.exponentialRampToValueAtTime(partial.gain, bellStart + 0.006);
    bellGain.gain.exponentialRampToValueAtTime(0.0004, bellStart + partial.decay);
    bell.connect(bellGain).connect(master);
    bell.start(bellStart);
    bell.stop(bellStart + partial.decay + 0.05);
  }
  const strikeLength = 0.011;
  const strike = context.createBufferSource();
  strike.buffer = makeNoise(strikeLength);
  const strikeFilter = context.createBiquadFilter();
  strikeFilter.type = "highpass";
  strikeFilter.frequency.value = 3200;
  const strikeGain = context.createGain();
  strikeGain.gain.setValueAtTime(0.05, bellStart);
  strikeGain.gain.exponentialRampToValueAtTime(0.0004, bellStart + strikeLength);
  strike.connect(strikeFilter).connect(strikeGain).connect(master);
  strike.start(bellStart);
  strike.stop(bellStart + strikeLength + 0.004);

  window.setTimeout(() => void context.close(), 1600);
}

