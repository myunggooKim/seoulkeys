type TargetCharState = { character: string; state: string };

/* Emits one <span> per character, exactly as before, except that the characters
 * inside a binding are enclosed in a `nowrap` run. Characters outside a binding
 * are left as direct children so the spaces between them remain break
 * opportunities — wrapping the whole sentence in runs removed them all and sent
 * the text out past the edge of the card. */
function renderTargetCharacters(characters: TargetCharState[], bindings: CharRange[]) {
  const nodes: React.ReactNode[] = [];
  const charSpan = (entry: TargetCharState, index: number) => (
    <span className={entry.state} data-gloss-index={index} key={`${entry.character}-${index}`}>{entry.character}</span>
  );

  let index = 0;
  let next = 0;
  while (index < characters.length) {
    const binding = bindings[next];
    if (binding && binding.start === index) {
      nodes.push(
        <span className="sentence-chunk" key={`bind-${binding.start}`}>
          {characters.slice(binding.start, binding.end).map((entry, offset) => charSpan(entry, binding.start + offset))}
        </span>,
      );
      index = binding.end;
      next += 1;
      continue;
    }
    nodes.push(charSpan(characters[index], index));
    index += 1;
  }
  return nodes;
}

